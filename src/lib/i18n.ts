export function detectSystemLanguage(): ResolvedLanguageCode {
  if (typeof navigator === 'undefined') return 'en';
  const candidates = navigator.languages?.length
    ? navigator.languages
    : [navigator.language || 'en'];

  for (const raw of candidates) {
    const lower = raw.toLowerCase();
    if (lower.startsWith('zh-tw') || lower.startsWith('zh-hk') || lower.startsWith('zh-hant')) {
      return 'zh-TW';
    }
    if (lower.startsWith('zh')) return 'zh-CN';
    const base = lower.split('-')[0] as ResolvedLanguageCode;
    if (base in TRANSLATIONS) {
      return base;
    }
  }
  return 'en';
}

export function resolveLanguage(choice: LanguageCode): ResolvedLanguageCode {
  if (choice === 'system') {
    return detectSystemLanguage();
  }
  return choice;
}
